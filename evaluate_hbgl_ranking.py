#!/usr/bin/env python3
"""Evaluate an HBGL ranking with the metric protocol used by HGCLR."""

from __future__ import annotations

import argparse
import json
import pickle
from collections import Counter
from pathlib import Path

from hbgl_ranking import evaluate_hbgl_hgclr_metrics


class _RankingUnpickler(pickle.Unpickler):
    """Ranking files contain only nested built-in dictionaries and numbers."""

    def find_class(self, module, name):
        raise pickle.UnpicklingError("HBGL ranking pickle cannot load {}.{}".format(module, name))


def _load_ranking(path):
    try:
        with Path(path).open("rb") as handle:
            ranking = _RankingUnpickler(handle).load()
    except (OSError, EOFError, pickle.UnpicklingError) as error:
        raise RuntimeError("could not safely load HBGL ranking artifact") from error
    if not isinstance(ranking, dict):
        raise ValueError("HBGL ranking artifact must be a dictionary")
    return ranking


def _load_pickle(path, description):
    try:
        with Path(path).open("rb") as handle:
            return pickle.load(handle)
    except (OSError, EOFError, pickle.UnpicklingError) as error:
        raise RuntimeError("could not load trusted canonical {}".format(description)) from error


def _document_id(sample, dataset_name):
    field = "text_idx" if dataset_name == "RCV1-103-H3" else "idx"
    value = sample.get(field)
    if not isinstance(value, int):
        raise ValueError("sample has invalid {}".format(field))
    return value


def _load_canonical_protocol(dataset_dir, dataset_name, fold):
    root = Path(dataset_dir)
    samples = _load_pickle(root / "samples.pkl", "samples")
    test_indices = _load_pickle(root / "fold_{}".format(fold) / "test.pkl", "test fold")
    relevance_raw = _load_pickle(root / "relevance_map.pkl", "relevance map")
    label_classes = _load_pickle(root / "label_cls.pkl", "label classes")
    text_classes = _load_pickle(root / "text_cls.pkl", "text classes")
    if not isinstance(samples, list) or not isinstance(test_indices, (list, tuple)):
        raise ValueError("canonical samples or test split is malformed")

    expected_documents = set()
    all_test_documents = set()
    relevance = {}
    for positional_index in test_indices:
        if not isinstance(positional_index, int) or positional_index < 0 or positional_index >= len(samples):
            raise ValueError("test fold contains invalid positional idx")
        document_id = _document_id(samples[positional_index], dataset_name)
        if document_id not in relevance_raw:
            raise ValueError("canonical relevance is missing test document {}".format(document_id))
        document_key = "text_{}".format(document_id)
        if document_key in all_test_documents:
            raise ValueError("test fold has duplicate external document ID {}".format(document_key))
        all_test_documents.add(document_key)
        labels = relevance_raw[document_id]
        if not labels:
            continue
        relevance[document_key] = {"label_{}".format(int(label_id)): 1.0 for label_id in labels}
        expected_documents.add(document_key)

    counts = Counter()
    for sample in samples:
        labels = sample.get("labels_ids")
        if not isinstance(labels, list) or not all(isinstance(label_id, int) for label_id in labels):
            raise ValueError("canonical sample has malformed labels_ids")
        counts.update(labels)
    return expected_documents, all_test_documents, relevance, label_classes, text_classes, dict(counts), len(samples)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ranking-file", required=True, help="HBGL .rnk generated by test.py")
    parser.add_argument("--dataset-dir", required=True, help="Canonical dataset root")
    parser.add_argument("--dataset-name", required=True, choices=("WOS-150-H2", "RCV1-103-H3"))
    parser.add_argument("--fold", required=True, type=int)
    parser.add_argument("--output-file", required=True)
    parser.add_argument("--thresholds", nargs="+", type=int, default=(1, 5, 10))
    parser.add_argument("--label-classes", nargs="+", default=("tail", "head"))
    parser.add_argument("--propensity-a", type=float, default=0.55)
    parser.add_argument("--propensity-b", type=float, default=1.5)
    args = parser.parse_args(argv)
    if any(threshold <= 0 for threshold in args.thresholds):
        parser.error("--thresholds must be positive")

    ranking = _load_ranking(args.ranking_file)
    expected, all_test_documents, relevance, label_classes, text_classes, label_counts, corpus_documents = _load_canonical_protocol(
        args.dataset_dir, args.dataset_name, args.fold
    )
    actual = set(ranking)
    missing = sorted(expected - actual)
    unexpected = sorted(actual - all_test_documents)
    if missing or unexpected:
        raise ValueError(
            "ranking/test-fold document coverage mismatch: missing={}, unexpected={}".format(
                missing[:5], unexpected[:5]
            )
        )
    ranking = {document_key: ranking[document_key] for document_key in expected}
    rows = evaluate_hbgl_hgclr_metrics(
        ranking,
        relevance,
        label_classes=label_classes,
        text_classes=text_classes,
        label_counts=label_counts,
        corpus_documents=corpus_documents,
        thresholds=args.thresholds,
        label_classes_to_evaluate=args.label_classes,
        propensity_a=args.propensity_a,
        propensity_b=args.propensity_b,
    )
    result = {
        "artifact_version": 1,
        "dataset": args.dataset_name,
        "fold": args.fold,
        "documents": len(expected),
        "thresholds": args.thresholds,
        "metric_protocol": "HGCLR EvalHelper-compatible head/tail ranking metrics",
        "propensity": {"A": args.propensity_a, "B": args.propensity_b, "corpus_documents": corpus_documents},
        "results": rows,
    }
    destination = Path(args.output_file)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps(result, sort_keys=True))
    return result


if __name__ == "__main__":
    main()
